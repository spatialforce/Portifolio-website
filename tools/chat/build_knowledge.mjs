// Builds api/_knowledge.js (the chatbot's system-prompt knowledge) from tools/chat/profile.md and src/pages/catalogue.ts.
// Run: node tools/chat/build_knowledge.mjs  (also runs before every build)
import { readFileSync, writeFileSync } from "node:fs";

const profile = readFileSync("tools/chat/profile.md", "utf8").trim();
const cat = readFileSync("src/pages/catalogue.ts", "utf8");

const SECTIONS = [
  ["CASESTUDIES", "Case studies", "/case-studies/"],
  ["WEBMAPS", "Web maps", "/maps/"],
  ["STORYMAPS", "Story maps", "/stories/"],
  ["DASHBOARDS", "Dashboards", "/dashboards/"],
];

function block(name) {
  const i = cat.indexOf(`export const ${name}`);
  if (i < 0) return "";
  const start = cat.indexOf("[", cat.indexOf("=", i));
  const end = cat.indexOf("\n];", start);
  return cat.slice(start, end);
}

function entries(src) {
  // each entry starts with "{ " at the start of a line (two-space indent)
  return src.split(/\n  \{ /).slice(1).map((e) => {
    const o = {};
    for (const m of e.matchAll(/(\w+):\s*"((?:[^"\\]|\\.)*)"/g)) if (!(m[1] in o)) o[m[1]] = m[2].replace(/\\"/g, '"');
    return o;
  }).filter((o) => o.slug && o.title);
}

let out = "";
let n = 0;
for (const [name, label, base] of SECTIONS) {
  const list = entries(block(name));
  out += `\n## ${label} (${list.length})\n`;
  for (const o of list) {
    const meta = [o.place, o.years].filter(Boolean).join(", ");
    let about = o.text || o.short || o.sub || "";
    if (about.length > 220) about = about.slice(0, about.lastIndexOf(" ", 220)) + "...";   // small prompt for free-tier token limits
    out += `- ${o.title}${meta ? ` [${meta}]` : ""}. ${base}${o.slug}. ${about}\n`;
    n++;
  }
}

const KNOWLEDGE = `${profile}\n\n# Portfolio work${out}`;
writeFileSync("api/_knowledge.js", `// Generated by tools/chat/build_knowledge.mjs. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(KNOWLEDGE)};\n`);
console.log(`knowledge: ${n} items, ${KNOWLEDGE.length} chars`);
